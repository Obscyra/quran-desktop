// Refreshes src/lib/reciters-qa.ts: the whole-surah recitations of quranicaudio.com that the app lists as "listen only".
// quranicaudio.com's list API sends no CORS headers, so the browser cannot read it; this script reads it instead.
// Only recitations in the usual (Hafs) reading of the whole Quran are kept, and only when sample surahs exist as files.
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'reciters-qa.ts');
const list = await (await fetch('https://quranicaudio.com/api/qaris')).json();
const SAMPLE = [1, 2, 36, 55, 67, 114];
const has = async (path, n) => {
  try {
    const r = await fetch(`https://download.quranicaudio.com/quran/${path}${String(n).padStart(3, '0')}.mp3`, { method: 'HEAD' });
    return r.ok;
  } catch {
    return false;
  }
};
const kept = [];
let next = 0;
const cands = list.filter((q) => q.section_id === 1 && q.file_formats.includes('mp3') && q.relative_path);
await Promise.all(Array.from({ length: 8 }, async () => {
  while (next < cands.length) {
    const q = cands[next++];
    const ok = (await Promise.all(SAMPLE.map((n) => has(q.relative_path, n)))).every(Boolean);
    if (ok) kept.push({ id: q.id, name: q.name.replace(/\s+/g, ' ').trim(), path: q.relative_path });
    else console.log('skipped', q.name);
  }
}));
kept.sort((a, b) => a.name.localeCompare(b.name) || a.id - b.id);
// two recordings under one name get a number, so the list never shows the same line twice
const seen = new Map();
for (const q of kept) {
  const n = (seen.get(q.name) ?? 0) + 1;
  seen.set(q.name, n);
  if (n > 1) q.name += ` (${n})`;
}
const rows = kept.map((q) => `  [${q.id}, ${JSON.stringify(q.name)}, ${JSON.stringify(q.path)}]`).join(',\n');
await writeFile(out, `// Generated by scripts/update-reciters.mjs from quranicaudio.com. [id, name, folder]. Do not edit by hand.\nexport const QURANICAUDIO: [number, string, string][] = [\n${rows}\n];\n`);
console.log(`${kept.length} of ${cands.length} kept`);
